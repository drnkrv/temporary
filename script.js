/* =========================================================================
   Embedded modal (pop-up)
   ========================================================================= */
function openEmbedModal(key) {
  const config = MODAL_EMBEDS[key];
  const overlay = document.getElementById("embed-modal");
  const frame = document.getElementById("embed-modal-frame");
  const title = document.getElementById("embed-modal-title");
  const openNew = document.getElementById("embed-modal-open-new");
  if (!config || !overlay || !frame) return;

  title.textContent = config.title;
  openNew.setAttribute("href", config.url);
  frame.setAttribute("src", config.url);

  overlay.classList.add("is-open");
  overlay.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
}

function closeEmbedModal() {
  const overlay = document.getElementById("embed-modal");
  const frame = document.getElementById("embed-modal-frame");
  if (!overlay || !overlay.classList.contains("is-open")) return;

  overlay.classList.remove("is-open");
  overlay.setAttribute("aria-hidden", "true");
  document.body.classList.remove("modal-open");
  if (frame) frame.setAttribute("src", "about:blank"); // stop loading, free memory
}

function bindEmbedModal() {
  document.addEventListener("click", (event) => {
    const trigger = event.target.closest("[data-modal-key]");
    if (trigger) {
      event.preventDefault();
      openEmbedModal(trigger.getAttribute("data-modal-key"));
      return;
    }

    // Click on the dimmed backdrop or the close (×) button closes the modal.
    if (event.target.id === "embed-modal" || event.target.closest("[data-modal-close]")) {
      closeEmbedModal();
    }
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeEmbedModal();
  });
}

/* =========================================================================
   About Us — auto-resize the embedded Apps Script page
   -------------------------------------------------------------------------
   The box in styles.css (.about-embed) starts at a fallback height. If the
   embedded page posts its real height back to us via postMessage, we grow
   or shrink the box to match — so the whole page is visible at once and
   nothing gets clipped or needs an internal scrollbar.

   This requires a small snippet inside the Apps Script HTML itself (it has
   to tell us its height; we can't read into another Google-hosted page
   from here). Add this near the end of the Apps Script's HTML output:

     <script>
       function reportHeight() {
         parent.postMessage(
           { type: "focalpoint:resize", height: document.documentElement.scrollHeight },
           "*"
         );
       }
       window.addEventListener("load", reportHeight);
       window.addEventListener("resize", reportHeight);
       if (window.ResizeObserver) {
         new ResizeObserver(reportHeight).observe(document.body);
       } else {
         setInterval(reportHeight, 800);
       }
     </script>

   Without that snippet, the box just stays at the CSS fallback height.
   ========================================================================= */
function bindAboutEmbedAutoResize() {
  const embedBox = document.querySelector(".about-embed");
  const frame = document.querySelector(".about-embed__frame");
  if (!embedBox || !frame) return;

  window.addEventListener("message", (event) => {
    const data = event.data;
    if (!data || data.type !== "focalpoint:resize" || typeof data.height !== "number") return;
    if (event.source !== frame.contentWindow) return; // must come from our own iframe

    const nextHeight = Math.min(Math.max(Math.round(data.height), 300), 6000);
    embedBox.style.height = `${nextHeight}px`;
  });
}

/* =========================================================================
   Global click handling for [data-nav] elements
   ========================================================================= */
function bindNavigation() {
  document.addEventListener("click", (event) => {
    const trigger = event.target.closest("[data-nav]");
    if (!trigger) return;

    event.preventDefault();
    navigateTo(trigger.getAttribute("data-nav"));
  });
}

/* =========================================================================
   Service flow: Concern Category → Type of Engagement → Specific Concerns
   -------------------------------------------------------------------------
   "Service" asks three things in order: WHAT the concern is about (Concern
   Category), WHO the requester is (Type of Engagement), then shows that
   concern's own list of specific concerns. Concern Category buttons carry
   data-concern="<key>" (the same <key> used everywhere else — DRIVE_LINKS,
   CONTACTS, the "<key>-menu" screen id). Picking one remembers the key and
   moves to Type of Engagement. Each Type of Engagement button carries
   data-engagement="plantilla" / "jocos"; either one sends the visitor on
   to that remembered concern's menu screen. Every concern's list is
   defined once and shown for both engagement types by default (see
   applyEngagementVisibility() for how to make one item engagement-only).
   Both screens also get a small breadcrumb chip confirming what was
   picked, so it's always clear the next list is the "corresponding" one.
   ========================================================================= */
let selectedConcern = null;
let selectedEngagement = null;

function bindConcernFlow() {
  document.addEventListener("click", (event) => {
    const concernBtn = event.target.closest("[data-concern]");
    if (concernBtn) {
      selectedConcern = concernBtn.getAttribute("data-concern");
      selectedEngagement = null;

      const label = CONCERN_LABELS[selectedConcern] || "";
      const chip = document.querySelector('[data-screen="type-of-engagement"] [data-selected-concern]');
      if (chip) chip.textContent = label;

      navigateTo("type-of-engagement");
      return;
    }

    const engagementBtn = event.target.closest("[data-engagement]");
    if (engagementBtn) {
      if (!selectedConcern) {
        // Reached this screen without picking a concern first (e.g. a
        // stale back/forward navigation) — send them back to pick one.
        navigateTo("concern-category");
        return;
      }
      selectedEngagement = engagementBtn.getAttribute("data-engagement");
      applyDriveLinks(selectedEngagement); // re-resolve links for the chosen engagement type
      applyEngagementVisibility(selectedEngagement); // show/hide any engagement-only items

      const destination = `${selectedConcern}-menu`;
      const chip = document.querySelector(`[data-screen="${destination}"] [data-flow-breadcrumb]`);
      if (chip) {
        const concernLabel = CONCERN_LABELS[selectedConcern] || "";
        const engagementLabel = ENGAGEMENT_LABELS[selectedEngagement] || "";
        chip.textContent = `${concernLabel} • ${engagementLabel}`;
      }

      navigateTo(destination);
    }
  });
}

