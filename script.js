/* =========================================================================
   Navigation
   ========================================================================= */
function navigateTo(screenId) {
  const target = document.querySelector(`.screen[data-screen="${screenId}"]`);
  if (!target) return;

  document.querySelectorAll(".screen.is-active").forEach((el) => el.classList.remove("is-active"));
  target.classList.add("is-active");
  window.scrollTo({ top: 0, behavior: "instant" in window ? "instant" : "auto" });
}

/* =========================================================================
   Wire up Google Drive links onto each menu-item
   -------------------------------------------------------------------------
   resolveLink() unwraps a DRIVE_LINKS entry into a single URL: plain
   strings pass straight through; { plantilla, jocos } entries resolve to
   whichever engagement was picked on the Type of Engagement screen,
   falling back to "plantilla" if that hasn't happened yet (e.g. the very
   first render, before Service has been used).
   ========================================================================= */
function resolveLink(value, engagement) {
  if (typeof value === "string") return value;
  if (value && typeof value === "object") {
    return value[engagement] || value.plantilla || value.jocos || "";
  }
  return "";
}

function applyDriveLinks(engagement) {
  document.querySelectorAll("[data-drive-group]").forEach((group) => {
    const groupKey = group.getAttribute("data-drive-group");
    const links = DRIVE_LINKS[groupKey] || {};
    group.querySelectorAll("[data-drive-key]").forEach((item) => {
      const key = item.getAttribute("data-drive-key");
      if (links[key] === undefined) return;
      const href = resolveLink(links[key], engagement);
      if (href) item.setAttribute("href", href);
    });
  });
}

/* =========================================================================
   Show/hide menu items that only apply to one Type of Engagement
   -------------------------------------------------------------------------
   Every concern's list (DRIVE_LINKS / the <a class="menu-item"> entries in
   index.html) is defined once and, by default, shown for BOTH Plantilla
   and JO/COS — that's the "same structure for every Service Category and
   Type of Engagement" the form follows. If a specific concern really
   should only appear under one engagement type, add
   data-engagement-only="plantilla" (or "jocos") to that <a> in index.html
   and this function will hide it whenever the other type is selected.
   ========================================================================= */
function applyEngagementVisibility(engagement) {
  document.querySelectorAll("[data-engagement-only]").forEach((item) => {
    const only = item.getAttribute("data-engagement-only");
    item.style.display = only === engagement ? "" : "none";
  });
}

